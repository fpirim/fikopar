import path from 'node:path'
import { test, expect, grid, clipped } from './fixtures'

const fixture = (name: string) => path.resolve(process.cwd(), 'e2e/fixtures', name)

test('imports a price list: preview, skip errors, apply, result', async ({ page }) => {
  await page.goto('/parts/import')
  await expect(page.getByRole('option', { name: /LISAKT/ })).toBeAttached()
  await page.getByLabel('File').setInputFiles(fixture('price-list.csv'))
  await page.getByRole('button', { name: 'Upload and preview' }).click()
  await expect(page).toHaveURL(/\/parts\/import\/\d+$/)
  const tabs = page.getByRole('tablist', { name: 'Change' })
  await expect(tabs.getByRole('tab', { name: /New\s*2/ })).toBeVisible()
  await expect(tabs.getByRole('tab', { name: /Price\s*1/ })).toBeVisible()
  await expect(tabs.getByRole('tab', { name: /Attributes\s*1/ })).toBeVisible()
  await expect(tabs.getByRole('tab', { name: /Errors\s*1/ })).toBeVisible()
  await expect(grid(page)).toContainText('HP-9001')
  expect(await clipped(page, ['stockNo', 'priceChangePct'])).toEqual([])

  await tabs.getByRole('tab', { name: /Errors/ }).click()
  await expect(grid(page)).toContainText('Invalid number')
  await expect(grid(page)).not.toContainText('HP-9001')
  await tabs.getByRole('tab', { name: /Price/ }).first().click()
  await expect(grid(page)).toContainText('+6.5%')

  await page.getByRole('button', { name: 'Continue to apply' }).click()
  const apply = page.getByRole('button', { name: 'Apply', exact: true })
  await expect(apply).toBeDisabled()
  await page.getByRole('checkbox', { name: 'Skip error rows' }).check()
  await apply.click()
  const dialog = page.getByRole('alertdialog')
  await expect(dialog).toContainText('2 new parts, 1 price changes')
  await dialog.getByRole('button', { name: 'Apply' }).click()
  const result = page.getByRole('list', { name: 'Result' })
  await expect(result).toContainText('Parts created2')
  await expect(result).toContainText('Prices added3')
  await expect(result).toContainText('Rows skipped1')
  await page.getByRole('link', { name: 'New import' }).click()
  await expect(page.getByRole('region', { name: 'Recent imports' })).toContainText('APPLIED')
})

test('maps unknown headers before the preview', async ({ page }) => {
  await page.goto('/parts/import')
  await page.getByLabel('File').setInputFiles(fixture('price-list-unmapped.csv'))
  await page.getByRole('button', { name: 'Upload and preview' }).click()
  await expect(page.getByRole('heading', { name: 'Map columns' })).toBeVisible()
  await expect(page.getByLabel('Stock no column')).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Stock no column').selectOption('Kod')
  await page.getByLabel('Description column').selectOption('Ad')
  await page.getByLabel('Price column').selectOption('Tutar')
  await page.getByRole('button', { name: 'Save mapping' }).click()
  await expect(page.getByRole('tab', { name: /New\s*1/ })).toBeVisible()
  await page.getByRole('button', { name: 'Edit mapping' }).click()
  await expect(page.getByLabel('Stock no column')).toHaveValue('Kod')
})

test.describe('tr', () => {
  test.use({ lang: 'tr' })
  test('preview columns fit in Turkish', async ({ page }) => {
    await page.goto('/parts/import')
    await page.getByLabel('Dosya').setInputFiles(fixture('price-list.csv'))
    await page.getByRole('button', { name: 'Yükle ve önizle' }).click()
    await expect(page.getByRole('tab', { name: /Yeni\s*2/ })).toBeVisible()
    await expect(grid(page)).toContainText('HP-9001')
    expect(await clipped(page, ['stockNo', 'priceChangePct'])).toEqual([])
    await page.getByRole('tab', { name: /Eksik/ }).click()
    await expect(grid(page)).toContainText('EKSİK')
    expect(await clipped(page, ['stockNo'])).toEqual([])
  })
})
